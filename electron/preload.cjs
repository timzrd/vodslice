const { contextBridge, ipcRenderer } = require('electron');

const on = (channel) => (cb) => {
  const fn = (_e, payload) => cb(payload);
  ipcRenderer.on(channel, fn);
  return () => ipcRenderer.removeListener(channel, fn);
};

contextBridge.exposeInMainWorld('api', {
  getSettings: () => ipcRenderer.invoke('settings:get'),
  setSettings: (patch) => ipcRenderer.invoke('settings:set', patch),
  replaceSetting: (key, value) => ipcRenderer.invoke('settings:replace', key, value),
  onSettings: on('settings'),
  history: () => ipcRenderer.invoke('history:get'),
  clearHistory: () => ipcRenderer.invoke('history:clear'),
  onHistory: on('history'),
  toolsStatus: () => ipcRenderer.invoke('tools:status'),
  updateTools: () => ipcRenderer.invoke('tools:update'),
  onTools: on('tools:progress'),
  probe: (url) => ipcRenderer.invoke('probe', url),
  frames: (cacheId, times, height) => ipcRenderer.invoke('frames', cacheId, times, height),
  peekName: (args) => ipcRenderer.invoke('name:peek', args),
  addJob: (spec) => ipcRenderer.invoke('job:add', spec),
  cancelJob: (id) => ipcRenderer.invoke('job:cancel', id),
  jobs: () => ipcRenderer.invoke('job:list'),
  clearJobs: () => ipcRenderer.invoke('job:clear'),
  onJob: on('job'),
  onJobRemoved: on('job:removed'),
  pickFolder: (current) => ipcRenderer.invoke('dialog:folder', current),
  pickFile: (filters) => ipcRenderer.invoke('dialog:file', filters),
  openPath: (p) => ipcRenderer.invoke('shell:open', p),
  showInFolder: (p) => ipcRenderer.invoke('shell:show', p),
  openExternal: (u) => ipcRenderer.invoke('shell:external', u),
  startDrag: (files) => ipcRenderer.send('drag:start', files),
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  writeClipboard: (t) => ipcRenderer.invoke('clipboard:write', t),
  toggleMini: () => ipcRenderer.invoke('mini:toggle'),
  miniState: () => ipcRenderer.invoke('mini:state'),
  onMiniState: on('mini:state'),
  miniResize: (h) => ipcRenderer.send('mini:resize', h),
  miniClose: () => ipcRenderer.send('mini:close'),
  showMain: () => ipcRenderer.send('main:show'),
  appInfo: () => ipcRenderer.invoke('app:info'),
  topazStatus: (force) => ipcRenderer.invoke('topaz:status', force),
  updateStatus: () => ipcRenderer.invoke('update:status'),
  updateCheck: () => ipcRenderer.invoke('update:check'),
  updateDownload: () => ipcRenderer.invoke('update:download'),
  updateInstall: () => ipcRenderer.invoke('update:install'),
  onUpdate: on('update'),
  premiereBuild: (o) => ipcRenderer.invoke('premiere:build', o),
  premiereOpen: (xml) => ipcRenderer.invoke('premiere:open', xml),
  premiereWords: (file) => ipcRenderer.invoke('premiere:words', file),
  premiereSaveWords: (file, words) => ipcRenderer.invoke('premiere:saveWords', file, words),
  onPremiere: on('premiere:progress'),
  whisperStatus: () => ipcRenderer.invoke('whisper:status'),
  parseInput: (text) => ipcRenderer.invoke('input:parse', text),
  browseChannel: (o) => ipcRenderer.invoke('browse:channel', o),
  browseTab: (o) => ipcRenderer.invoke('browse:tab', o),
  browseMore: (o) => ipcRenderer.invoke('browse:more', o),
  browseSearch: (o) => ipcRenderer.invoke('browse:search', o),
  chatActivity: (o) => ipcRenderer.invoke('chat:activity', o),
  onChatProgress: on('chat:progress'),
  projects: () => ipcRenderer.invoke('projects:list'),
  projectGet: (id) => ipcRenderer.invoke('projects:get', id),
  projectSave: (p) => ipcRenderer.invoke('projects:save', p),
  projectRemove: (id) => ipcRenderer.invoke('projects:remove', id),
  projectRename: (id, name) => ipcRenderer.invoke('projects:rename', id, name),
  loginRunning: (browser) => ipcRenderer.invoke('login:running', browser),
  loginImport: (browser) => ipcRenderer.invoke('login:import', browser),
  loginFile: () => ipcRenderer.invoke('login:file'),
  loginClear: () => ipcRenderer.invoke('login:clear'),
  // hidden chat-render window
  onChatRenderJob: on('chatrender:job'),
  chatRenderReady: () => ipcRenderer.send('chatrender:ready'),
  chatRenderStart: (id, total) => ipcRenderer.send('chatrender:start', id, total),
  chatRenderFrame: (id, i, t, bytes) => ipcRenderer.send('chatrender:frame', id, i, t, bytes),
  chatRenderDone: (id) => ipcRenderer.send('chatrender:done', id),
  chatRenderError: (id, msg) => ipcRenderer.send('chatrender:error', id, msg),
});
